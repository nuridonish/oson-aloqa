    val default: Country = all.first()

    fun search(query: String): List<Country> {
        val q = query.trim().lowercase(Locale.ROOT)
        if (q.isEmpty()) return all
        return all.filter {
            it.name.lowercase(Locale.ROOT).contains(q) || it.code.startsWith(q.removePrefix("+"))
        }
    }

    fun byCode(code: String): Country? = all.firstOrNull { it.code == code }

    fun normalize(national: String, code: String): String? {
        val digits = national.filter { it.isDigit() }
        if (digits.length < 6 || digits.length > 15) return null
        val trimmed = digits.dropWhile { it == '0' }
        if (trimmed.length < 6) return null
        return "+$code$trimmed"
    }
